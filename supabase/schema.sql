create or replace function public.cm_ref_top(n int default 8) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(x), '[]'::jsonb) from (
    select s.first_name as name, s.email, count(f.id)::int as signups,
      (select count(distinct b.client_id) from public.bookings b join public.profiles q on q.id = b.client_id where q.referred_by = s.id and b.status = 'confirmed')::int as booked
    from public.profiles s join public.profiles f on f.referred_by = s.id
    where public.is_team() group by s.id order by count(f.id) desc limit n) x $$;
