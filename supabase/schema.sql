create or replace function public.cm_team_pro(p_id bigint, p_do text, p_reason text default '') returns text
language plpgsql security definer set search_path = public as $$
declare v_pro public.pros;
begin
  if not public.is_team() then raise exception 'Réservé à l''équipe.'; end if;
  select * into v_pro from public.pros where id = p_id;
  if not found then raise exception 'Coiffeur introuvable.'; end if;
  if p_do = 'publish' then
    update public.pros set status = 'publish', refused = '' where id = p_id;
    perform public.cm_mail(v_pro.owner, 'pro_online', 'Votre profil est en ligne', 'Bonne nouvelle : votre profil ' || v_pro.name || ' est visible par les clientes.');
    return 'Profil publié. Le coiffeur est prévenu par e-mail.';
  elsif p_do = 'refuse' then
    if char_length(trim(coalesce(p_reason, ''))) < 5 then raise exception 'Expliquez au coiffeur ce qu''il doit corriger.'; end if;
    update public.pros set status = 'draft', refused = left(trim(p_reason), 400) where id = p_id;
    perform public.cm_mail(v_pro.owner, 'pro_refused', 'Votre profil est à compléter', trim(p_reason));
    return 'Profil renvoyé au coiffeur avec votre message.';
  elsif p_do = 'unpublish' then
    update public.pros set status = 'draft' where id = p_id; return 'Profil retiré de la recherche.';
  elsif p_do in ('verify', 'unverify') then
    update public.pros set verified = (p_do = 'verify') where id = p_id;
    return case when p_do = 'verify' then 'Badge « Diplôme vérifié » attribué.' else 'Badge retiré.' end;
  end if;
  raise exception 'Action inconnue.';
end $$;

create or replace function public.cm_team_report(p_id bigint, p_do text) returns text
language plpgsql security definer set search_path = public as $$
declare x public.reports; v_msg text;
begin
  if not public.is_team() then raise exception 'Réservé à l''équipe.'; end if;
  select * into x from public.reports where id = p_id;
  if not found then raise exception 'Signalement introuvable.'; end if;
  if p_do = 'hide_review' and x.type = 'review' then update public.reviews set hidden = true where id = x.target_id; v_msg := 'Avis masqué.';
  elsif p_do = 'unpublish_pro' then update public.pros set status = 'draft' where id = x.pro_id; v_msg := 'Profil retiré de la recherche.';
  elsif p_do = 'keep' then v_msg := 'Signalement classé, rien n''a été modifié.';
  else raise exception 'Action inconnue.'; end if;
  update public.reports set status = 'done' where id = p_id;
  return v_msg;
end $$;

create or replace function public.cm_team_cancel(p_id bigint) returns text
language plpgsql security definer set search_path = public as $$
declare b public.bookings;
begin
  if not public.is_team() then raise exception 'Réservé à l''équipe.'; end if;
  select * into b from public.bookings where id = p_id;
  if not found then raise exception 'Rendez-vous introuvable.'; end if;
  if b.status not in ('pending', 'confirmed') or (b.slot_date + b.slot_hour::time) <= public.cm_now() then raise exception 'Ce rendez-vous ne peut plus être annulé.'; end if;
  perform public.cm_set_status(p_id, 'cancelled');
  perform public.cm_mail(b.client_id, 'cancelled', 'Votre rendez-vous est annulé', 'L''équipe Coiff''Match a annulé votre rendez-vous du ' || public.cm_date_label(b.slot_date) || '.');
  perform public.cm_mail((select owner from public.pros where id = b.pro_id), 'cancelled', 'Un rendez-vous est annulé', 'L''équipe Coiff''Match a annulé le rendez-vous du ' || public.cm_date_label(b.slot_date) || ' à ' || b.slot_hour || '.');
  return 'Rendez-vous annulé. La cliente et le coiffeur sont prévenus.';
end $$;

