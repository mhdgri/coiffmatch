create or replace function public.cm_send_message(p_pro bigint, p_client uuid, p_body text) returns void
language plpgsql security definer set search_path = public as $$
declare v_pro public.pros; v_body text := left(trim(coalesce(p_body, '')), 1000); v_to uuid; v_unread int; v_from text;
begin
  select * into v_pro from public.pros where id = p_pro;
  if not found or not (p_client = auth.uid() or v_pro.owner = auth.uid()) then raise exception 'Conversation introuvable.'; end if;
  if v_pro.owner = p_client and not v_pro.is_example then raise exception 'Vous ne pouvez pas vous écrire à vous-même.'; end if;
  if v_pro.status <> 'publish' and p_client = auth.uid() then raise exception 'Ce coiffeur n''est pas disponible.'; end if;
  if v_body = '' then raise exception 'Écrivez votre message.'; end if;
  if (select count(*) from public.messages where sender_id = auth.uid() and created > now() - interval '10 minutes') >= 40 then
    raise exception 'Trop de messages en peu de temps. Réessayez dans quelques minutes.';
  end if;
  insert into public.messages (pro_id, client_id, sender_id, body) values (p_pro, p_client, auth.uid(), v_body);
  v_to := case when auth.uid() = p_client then v_pro.owner else p_client end;
  select count(*) into v_unread from public.messages where pro_id = p_pro and client_id = p_client and sender_id = auth.uid() and read_at is null;
  if v_unread = 1 then
    v_from := case when auth.uid() = p_client then (select first_name from public.profiles where id = p_client) else v_pro.name end;
    perform public.cm_mail(v_to, 'message', 'Nouveau message de ' || coalesce(v_from, 'Coiff''Match'), 'Vous avez reçu un message sur Coiff''Match : ouvrez votre messagerie pour le lire.');
  end if;
end $$;

