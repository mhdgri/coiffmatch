create or replace function public.cm_waitlist_notify(p_pro bigint, p_date date, p_except uuid) returns void
language plpgsql security definer set search_path = public as $$
declare w record; v_name text;
begin
  if p_date < public.cm_now()::date then return; end if;
  select name into v_name from public.pros where id = p_pro;
  for w in select * from public.waitlist where pro_id = p_pro and slot_date = p_date and not notified and client_id is distinct from p_except loop
    perform public.cm_mail(w.client_id, 'waitlist', 'Un créneau s''est libéré chez ' || v_name,
      'Bonne nouvelle : un créneau vient de se libérer le ' || public.cm_date_label(p_date) || ' chez ' || v_name || '. Réservez vite avant qu''il ne soit repris.');
    update public.waitlist set notified = true where id = w.id;
  end loop;
end $$;

create or replace function public.cm_waitlist_add(p_pro bigint, p_date date, p_presta text) returns text
language plpgsql security definer set search_path = public as $$
declare v_id bigint; s public.settings := public.cm_settings();
begin
  if auth.uid() is null then raise exception 'Connectez-vous pour continuer.'; end if;
  if public.my_role() = 'coiffeur' then raise exception 'La liste d''attente est réservée aux comptes client.'; end if;
  if not exists (select 1 from public.pros where id = p_pro and status = 'publish') then raise exception 'Coiffeur introuvable.'; end if;
  if p_date is null or p_date <= public.cm_now()::date or p_date > public.cm_now()::date + s.booking_days then
    raise exception 'Choisissez un jour dans les semaines à venir.';
  end if;
  if (select count(*) from public.waitlist where client_id = auth.uid() and slot_date >= public.cm_now()::date and not notified) >= 5 then
    raise exception 'Vous êtes déjà en attente sur 5 jours. Retirez-en un depuis « Mes rendez-vous ».';
  end if;
  select id into v_id from public.waitlist where pro_id = p_pro and client_id = auth.uid() and slot_date = p_date;
  if v_id is not null then update public.waitlist set notified = false where id = v_id;
  else insert into public.waitlist (pro_id, client_id, slot_date, presta_k) values (p_pro, auth.uid(), p_date, left(coalesce(p_presta, ''), 10));
  end if;
  return case when (select emails from public.settings where id = 1)
    then 'C''est noté : vous recevrez un e-mail si un créneau se libère le ' || public.cm_date_label(p_date) || '.'
    else 'C''est noté : ce jour apparaît dans « Mes rendez-vous ». Revenez voir si un créneau se libère le ' || public.cm_date_label(p_date) || '.' end;
end $$;

