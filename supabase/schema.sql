create or replace function public.cm_pro_photos(p_action text, p_value jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_pro public.pros; v_photos jsonb; v_out jsonb := '[]'::jsonb; x jsonb;
begin
  select * into v_pro from public.pros where owner = auth.uid() and not is_example order by id limit 1;
  if not found then raise exception 'Enregistrez d''abord votre profil, puis ajoutez vos photos.'; end if;
  v_photos := v_pro.photos;
  if p_action = 'add' then
    if jsonb_array_length(v_photos) >= 12 then raise exception 'Vous avez atteint le maximum de 12 photos.'; end if;
    if coalesce(p_value ->> 'path', '') not like auth.uid()::text || '/%' then raise exception 'Photo introuvable.'; end if;
    v_photos := v_photos || jsonb_build_array(jsonb_build_object('id', (extract(epoch from clock_timestamp()) * 1000)::bigint, 'url', p_value ->> 'url', 'path', p_value ->> 'path', 'tag', ''));
  elsif p_action in ('delete', 'tag') then
    if not exists (select 1 from jsonb_array_elements(v_photos) e where (e ->> 'id')::bigint = (p_value ->> 'id')::bigint) then raise exception 'Photo introuvable.'; end if;
    for x in select * from jsonb_array_elements(v_photos) loop
      if (x ->> 'id')::bigint = (p_value ->> 'id')::bigint then
        if p_action = 'delete' then continue; end if;
        x := x || jsonb_build_object('tag', case when p_value ->> 'tag' in ('avant', 'apres') then p_value ->> 'tag' else '' end);
      end if;
      v_out := v_out || jsonb_build_array(x);
    end loop;
    v_photos := v_out;
  end if;
  update public.pros set photos = v_photos where id = v_pro.id;
  return v_photos;
end $$;

create or replace function public.cm_note(p_client uuid, p_note text) returns text
language plpgsql security definer set search_path = public as $$
declare v_pro bigint; v_note text := left(trim(coalesce(p_note, '')), 1000);
begin
  select id into v_pro from public.pros where owner = auth.uid() and not is_example order by id limit 1;
  if v_pro is null or not exists (select 1 from public.bookings where pro_id = v_pro and client_id = p_client) then
    raise exception 'Cette personne n''a pas encore pris rendez-vous avec vous.';
  end if;
  delete from public.notes where pro_id = v_pro and client_id = p_client;
  if v_note <> '' then insert into public.notes (pro_id, client_id, note) values (v_pro, p_client, v_note); end if;
  return v_note;
end $$;

