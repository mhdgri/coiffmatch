create or replace function public.cm_delete_account() returns void
language plpgsql security definer set search_path = public, auth as $$
declare b record;
begin
  if auth.uid() is null then raise exception 'Connectez-vous pour continuer.'; end if;
  if public.my_role() = 'admin' then raise exception 'Un compte de l''équipe ne peut pas être supprimé d''ici.'; end if;
  for b in select id from public.bookings where client_id = auth.uid() and status in ('pending', 'confirmed') and (slot_date + slot_hour::time) > public.cm_now() loop
    perform public.cm_set_status(b.id, 'cancelled');
  end loop;
  delete from public.pros where owner = auth.uid() and not is_example;
  -- Rendez-vous et avis passés gardés sans données personnelles.
  update public.bookings set first_name = '', phone = '', address = '', hair_profile = '{}'::jsonb where client_id = auth.uid();
  update public.reviews set first_name = 'Ancienne cliente' where client_id = auth.uid();
  delete from auth.users where id = auth.uid();
end $$;

