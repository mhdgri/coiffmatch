-- Message depuis la page Contact.
create or replace function public.cm_contact(p_name text, p_email text, p_subject text, p_body text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if char_length(trim(coalesce(p_name, ''))) < 2 then raise exception 'Indiquez votre nom.'; end if;
  if coalesce(p_email, '') !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Indiquez une adresse e-mail valide.'; end if;
  if char_length(trim(coalesce(p_body, ''))) < 10 then raise exception 'Écrivez votre message (10 caractères minimum).'; end if;
  if (select count(*) from public.contact_messages where created > now() - interval '10 minutes' and (email = lower(p_email) or user_id = auth.uid())) >= 3 then
    raise exception 'Trop de messages en peu de temps. Réessayez dans quelques minutes.';
  end if;
  insert into public.contact_messages (user_id, name, email, subject, body)
  values (auth.uid(), left(trim(p_name), 80), lower(trim(p_email)), left(coalesce(p_subject, ''), 80), left(trim(p_body), 3000));
  -- Prévenir l'équipe par e-mail (envoyé si les e-mails sont branchés).
  perform public.cm_mail(id, 'contact', 'Nouveau message de contact : ' || left(trim(p_name), 80),
    'De : ' || left(trim(p_name), 80) || ' <' || lower(trim(p_email)) || '>' || chr(10) || chr(10) || left(trim(p_body), 3000) ||
    chr(10) || chr(10) || 'Répondez directement à cette adresse. Le message est aussi dans l''espace équipe, onglet Messages.')
  from public.profiles where role = 'admin';
end $$;
grant execute on function public.cm_contact(text, text, text, text) to anon, authenticated;

-- Demandes trop anciennes → « sans réponse » ; rappels la veille. Appelée par pg_cron et à chaque visite.
create or replace function public.cm_tick() returns void
language plpgsql security definer set search_path = public as $$
declare b record; v_now timestamp := public.cm_now();
begin
  for b in select * from public.bookings where status = 'pending'
    and (created <= now() - interval '24 hours' or (slot_date + slot_hour::time) <= v_now + interval '2 hours') for update skip locked
  loop
    update public.bookings set status = 'expired', updated = now() where id = b.id;
    perform public.cm_mail(b.client_id, 'expired', 'Votre demande n''a pas reçu de réponse',
      'Le coiffeur n''a pas répondu à temps à votre demande du ' || public.cm_date_label(b.slot_date) || ' à ' || b.slot_hour || '. Choisissez un autre créneau ou un autre coiffeur.');
    perform public.cm_waitlist_notify(b.pro_id, b.slot_date, b.client_id);
  end loop;
  for b in select * from public.bookings where status = 'confirmed' and not reminded
    and (slot_date + slot_hour::time) between v_now + interval '1 hour' and v_now + interval '24 hours' for update skip locked
  loop
    update public.bookings set reminded = true where id = b.id;
    if b.created < now() - interval '2 hours' and not (select is_example from public.pros where id = b.pro_id) then
      perform public.cm_mail(b.client_id, 'reminder', 'Rappel : votre rendez-vous coiffure demain',
        b.label || ' le ' || public.cm_date_label(b.slot_date) || ' à ' || b.slot_hour || '.');
    end if;
  end loop;
  delete from public.waitlist where slot_date < v_now::date;
end $$;
grant execute on function public.cm_tick() to anon, authenticated;

