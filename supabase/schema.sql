-- Vue d'un profil (compteur par jour, sans donnée personnelle).
create or replace function public.cm_view(p_pro bigint) returns void
language plpgsql security definer set search_path = public as $$
declare d text := to_char(public.cm_now(), 'YYYY-MM-DD');
begin
  if public.owns_pro(p_pro) or public.is_team() then return; end if;
  if not exists (select 1 from public.pros where id = p_pro and status = 'publish') then return; end if;
  insert into public.pro_private (pro_id) values (p_pro) on conflict do nothing;
  update public.pro_private set views = (
    select coalesce(jsonb_object_agg(k, v), '{}'::jsonb) from (
      select key k, value v from jsonb_each(views) where key >= to_char(public.cm_now() - interval '90 days', 'YYYY-MM-DD') and key <> d
      union all select d, to_jsonb(coalesce((views ->> d)::int, 0) + 1)
    ) x) where pro_id = p_pro;
end $$;
grant execute on function public.cm_view(bigint) to anon, authenticated;

