create or replace function public.cm_pro_save(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid(); v_id bigint; v_status text; v_new boolean; v_name text := left(trim(coalesce(p ->> 'name', '')), 40);
  v_mode text := case when p ->> 'mode' = 'domicile' then 'domicile' else 'salon' end;
  v_presta jsonb := '[]'::jsonb; x jsonb; v_row jsonb; v_plus jsonb; n int := 0; v_staff jsonb := '[]'::jsonb; m jsonb; v_used text[] := '{}';
  v_week jsonb := '[]'::jsonb; d int; v_hours text[] := array['8:00','8:30','9:00','9:30','10:00','10:30','11:00','11:15','11:30','12:00','13:00','13:30','14:00','14:30','15:00','15:30','16:00','16:15','16:30','17:00','17:30','18:00','18:30','19:00','19:30','20:00'];
  v_keys text[]; v_k text; i int; v_days jsonb; v_place text := left(trim(coalesce(p ->> 'place', '')), 60); v_slug text;
begin
  if v_uid is null then raise exception 'Connectez-vous pour continuer.'; end if;
  if public.my_role() not in ('coiffeur', 'admin') then
    raise exception 'Ce compte est un compte client. Créez un compte coiffeur sur l''Espace coiffeur pour publier un profil.';
  end if;
  if v_name = '' then raise exception 'Indiquez le nom affiché sur votre profil.'; end if;
  if v_place = '' then raise exception 'Indiquez votre ville ou votre quartier.'; end if;
  if v_mode = 'salon' and char_length(trim(coalesce(p ->> 'address', ''))) < 8 then raise exception 'Indiquez l''adresse du salon (numéro, rue, code postal, ville).'; end if;
  if cardinality(public.cm_clean_list(p -> 'hair', array['raides','ondules','boucles','frises','crepus'])) = 0 then
    raise exception 'Choisissez au moins un type de cheveux que vous maîtrisez.';
  end if;
  -- Prestations
  for x in select * from jsonb_array_elements(case when jsonb_typeof(p -> 'presta') = 'array' then p -> 'presta' else '[]'::jsonb end) limit 12 loop
    if char_length(trim(coalesce(x ->> 'label', ''))) = 0 then continue; end if;
    begin
      if round((x ->> 'price')::numeric) < 1 or round((x ->> 'price')::numeric) > 999 then continue; end if;
    exception when others then continue; end;
    n := n + 1;
    v_row := jsonb_build_object('k', 'p' || n, 'label', left(trim(x ->> 'label'), 60),
      'service', case when x ->> 'service' in ('coupe','coupe-soin','tresses','couleur','autre') then x ->> 'service' else 'autre' end,
      'dur', greatest(15, least(480, coalesce(nullif(x ->> 'dur', '')::numeric, 60)::int)), 'price', round((x ->> 'price')::numeric)::int);
    v_plus := '{}'::jsonb;
    foreach v_k in array array['mi-long', 'long'] loop
      begin
        if round(coalesce(nullif(x -> 'plus' ->> v_k, ''), '0')::numeric) > 0 then
          v_plus := v_plus || jsonb_build_object(v_k, least(300, round((x -> 'plus' ->> v_k)::numeric)::int));
        end if;
      exception when others then null; end;
    end loop;
    if v_plus <> '{}'::jsonb then v_row := v_row || jsonb_build_object('plus', v_plus); end if;
    begin
      if coalesce(nullif(x ->> 'every', ''), '0')::int > 0 then v_row := v_row || jsonb_build_object('every', least(52, (x ->> 'every')::int)); end if;
    exception when others then null; end;
    v_presta := v_presta || jsonb_build_array(v_row);
  end loop;
  -- Horaires
  for d in 0..6 loop
    v_week := v_week || jsonb_build_array(coalesce((select jsonb_agg(h order by array_position(v_hours, h)) from jsonb_array_elements_text(coalesce(p -> 'week' -> d, '[]'::jsonb)) h where h = any (v_hours)), '[]'::jsonb));
  end loop;
  -- Équipe (salon seulement)
  select array_agg(e ->> 'k') into v_keys from jsonb_array_elements(v_presta) e;
  if v_mode = 'salon' and jsonb_typeof(p -> 'staff') = 'array' then
    for m in select * from jsonb_array_elements(p -> 'staff') limit 8 loop
      if char_length(trim(coalesce(m ->> 'name', ''))) = 0 then continue; end if;
      v_k := case when coalesce(m ->> 'k', '') ~ '^s\d{1,3}$' and not (m ->> 'k') = any (v_used) then m ->> 'k' else '' end;
      if v_k = '' then i := 1; loop v_k := 's' || i; exit when not v_k = any (v_used); i := i + 1; end loop; end if;
      v_used := v_used || v_k;
      select coalesce(jsonb_agg(distinct dd::int), '[0,1,2,3,4,5,6]'::jsonb) into v_days from jsonb_array_elements_text(coalesce(m -> 'days', '[0,1,2,3,4,5,6]'::jsonb)) dd where dd ~ '^[0-6]$';
      v_staff := v_staff || jsonb_build_array(jsonb_build_object('k', v_k, 'name', left(trim(m ->> 'name'), 30),
        'presta', coalesce((select jsonb_agg(z) from jsonb_array_elements_text(coalesce(m -> 'presta', '[]'::jsonb)) z where z = any (coalesce(v_keys, '{}'))), '[]'::jsonb),
        'days', v_days));
    end loop;
  end if;

  select id, status into v_id, v_status from public.pros where owner = v_uid and not is_example order by id limit 1;
  v_new := v_id is null;
  if v_new then
    insert into public.pros (owner, name, status) values (v_uid, v_name, 'pending') returning id into v_id;
    insert into public.pro_private (pro_id) values (v_id) on conflict do nothing;
    update public.profiles set role = case when role = 'admin' then role else 'coiffeur' end where id = v_uid;
  end if;
  v_slug := public.cm_slugify(v_name || ' ' || v_place) || '-' || v_id;
  update public.pros set
    name = v_name, slug = v_slug, mode = v_mode, place = v_place,
    address = case when v_mode = 'salon' then left(trim(coalesce(p ->> 'address', '')), 120) else '' end,
    zones = case when v_mode = 'domicile' then (select coalesce(array_agg(distinct left(trim(z), 40)) filter (where trim(z) <> ''), '{}') from (
              select z from jsonb_array_elements_text(case when jsonb_typeof(p -> 'zones') = 'array' then p -> 'zones' else to_jsonb(string_to_array(coalesce(p ->> 'zones', ''), ',')) end) z limit 12) q) else '{}' end,
    travel = case when v_mode = 'domicile' then greatest(0, least(50, coalesce(nullif(p ->> 'travel', '')::numeric, 0)::int)) else 0 end,
    bio = left(trim(coalesce(p ->> 'bio', '')), 400),
    hair = public.cm_clean_list(p -> 'hair', array['raides','ondules','boucles','frises','crepus']),
    tags = (select coalesce(array_agg(left(trim(t), 30)), '{}') from (select t from jsonb_array_elements_text(case when jsonb_typeof(p -> 'tags') = 'array' then p -> 'tags' else to_jsonb(string_to_array(coalesce(p ->> 'tags', ''), ',')) end) t where trim(t) <> '' limit 6) q),
    skills = (public.cm_clean_list(p -> 'skills', array['crepus','coupe-sec','locks','tresses','twists','perruques','transition','couleur','soins','enfants']))[1:6],
    diploma = case when p ->> 'diploma' in ('', 'CAP', 'BP', 'BM', 'Autre') then p ->> 'diploma' else '' end,
    presta = v_presta, staff = v_staff, week = v_week,
    off = (select coalesce(array_agg(distinct o), '{}') from (select o from jsonb_array_elements_text(case when jsonb_typeof(p -> 'off') = 'array' then p -> 'off' else '[]'::jsonb end) o where o ~ '^\d{4}-\d{2}-\d{2}$' limit 60) q),
    geo = case when jsonb_typeof(p -> 'geo') = 'array' and jsonb_array_length(p -> 'geo') = 2 then array[(p -> 'geo' ->> 0)::float8, (p -> 'geo' ->> 1)::float8] else geo end,
    status = case when status = 'draft' then 'pending' else status end
  where id = v_id;
  if jsonb_array_length(v_presta) = 0 then
    update public.pros set status = 'pending' where id = v_id and status = 'publish';
    raise exception 'Ajoutez au moins une prestation avec un nom et un prix.';
  end if;
  if v_new or v_status = 'draft' then
    perform public.cm_mail(v_uid, 'pro_submitted', 'Votre profil est envoyé', 'Merci ! L''équipe Coiff''Match vérifie votre profil et le met en ligne rapidement.');
  end if;
  return v_id;
end $$;

