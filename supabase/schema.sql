create or replace function public.cm_overlaps(p_pro bigint, p_date date, p_hour text, p_dur int, p_staff text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.bookings b where b.pro_id = p_pro and b.slot_date = p_date and b.status in ('pending', 'confirmed')
    and (p_staff = '' or b.staff = p_staff)
    and public.cm_minutes(p_hour) < public.cm_minutes(b.slot_hour) + greatest(15, b.dur)
    and public.cm_minutes(b.slot_hour) < public.cm_minutes(p_hour) + greatest(15, p_dur)) $$;

create or replace function public.cm_book(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid(); v_prof public.profiles; v_pro public.pros; v_presta jsonb; v_member jsonb;
  v_staff text := ''; v_sname text := ''; v_date date; v_hour text := coalesce(p ->> 'hour', '');
  v_slot timestamp; s public.settings := public.cm_settings(); v_now timestamp := public.cm_now();
  v_first text; v_phone text; v_address text; v_home boolean; v_length text := coalesce(p ->> 'length', '');
  v_price int; v_photos jsonb := '[]'::jsonb; v_id bigint; v_hair text; v_dow int; ph jsonb;
begin
  if v_uid is null then raise exception 'Connectez-vous pour continuer.'; end if;
  select * into v_prof from public.profiles where id = v_uid;
  if v_prof.role = 'coiffeur' then raise exception 'Les comptes coiffeur ne réservent pas : utilisez un compte client avec une autre adresse e-mail.'; end if;
  if (select count(*) from public.bookings where client_id = v_uid and created > now() - interval '10 minutes') >= 15 then
    raise exception 'Trop de demandes en peu de temps. Réessayez dans quelques minutes.';
  end if;
  select * into v_pro from public.pros where id = (p ->> 'pro_id')::bigint and status = 'publish';
  if not found then raise exception 'Ce coiffeur n''est pas disponible.'; end if;
  if v_pro.owner = v_uid and not v_pro.is_example then raise exception 'Vous ne pouvez pas réserver sur votre propre profil.'; end if;
  select x into v_presta from jsonb_array_elements(v_pro.presta) x where x ->> 'k' = coalesce(p ->> 'presta', '');
  if v_presta is null then raise exception 'Choisissez une prestation.'; end if;
  begin v_date := (p ->> 'date')::date; exception when others then v_date := null; end;
  if v_date is null or v_hour !~ '^\d{1,2}:\d{2}$' then raise exception 'Ce créneau n''est pas proposé par le coiffeur.'; end if;
  v_dow := extract(dow from v_date)::int;
  if v_pro.mode = 'salon' and jsonb_array_length(v_pro.staff) > 0 then
    select m into v_member from jsonb_array_elements(v_pro.staff) m where m ->> 'k' = coalesce(p ->> 'staff', '');
    if v_member is null or (jsonb_array_length(coalesce(v_member -> 'presta', '[]')) > 0 and not (v_member -> 'presta') ? (v_presta ->> 'k')) then
      raise exception 'Choisissez le coiffeur avec qui vous voulez prendre rendez-vous.';
    end if;
    if not (v_member -> 'days') @> to_jsonb(v_dow) then raise exception 'Ce créneau n''est pas proposé par le coiffeur.'; end if;
    v_staff := v_member ->> 'k'; v_sname := v_member ->> 'name';
  end if;
  if v_date::text = any (v_pro.off) or not (public.cm_week(v_pro) -> v_dow) ? v_hour then
    raise exception 'Ce créneau n''est pas proposé par le coiffeur.';
  end if;
  v_slot := v_date + v_hour::time;
  if v_slot <= v_now or v_slot > v_now + make_interval(days => s.booking_days + 1) then raise exception 'Choisissez un créneau dans les prochains jours.'; end if;
  v_first := left(trim(coalesce(p ->> 'first_name', '')), 40);
  if v_first = '' then raise exception 'Indiquez votre prénom.'; end if;
  v_phone := regexp_replace(coalesce(p ->> 'phone', ''), '[^0-9+]', '', 'g');
  if not (v_phone ~ '^0[1-9][0-9]{8}$' or v_phone ~ '^\+[1-9][0-9]{7,14}$') then
    raise exception 'Indiquez un numéro de téléphone valide : le coiffeur pourra vous joindre le jour du rendez-vous.';
  end if;
  v_home := v_pro.mode = 'domicile';
  v_address := left(trim(coalesce(p ->> 'address', '')), 200);
  if v_home and char_length(v_address) < 8 then raise exception 'Indiquez l''adresse où le coiffeur doit venir (numéro, rue, ville).'; end if;
  if not v_home then v_address := ''; end if;
  if v_length not in ('', 'court', 'mi-long', 'long') then v_length := ''; end if;
  if coalesce(v_presta -> 'plus', '{}'::jsonb) <> '{}'::jsonb and jsonb_typeof(v_presta -> 'plus') = 'object' and v_length = '' then
    raise exception 'Indiquez la longueur de vos cheveux : le prix de cette prestation en dépend.';
  end if;
  v_price := (v_presta ->> 'price')::int + coalesce((v_presta -> 'plus' ->> v_length)::int, 0);
  v_hair := case when p ->> 'hair' in ('raides', 'ondules', 'boucles', 'frises', 'crepus') then p ->> 'hair' else '' end;
  -- Photos des cheveux : au plus 3, rangées dans le dossier de la cliente.
  for ph in select * from jsonb_array_elements(coalesce(p -> 'photos', '[]'::jsonb)) limit 3 loop
    if ph ->> 'path' like v_uid::text || '/%' then v_photos := v_photos || jsonb_build_array(jsonb_build_object('path', ph ->> 'path')); end if;
  end loop;
  perform pg_advisory_xact_lock(v_pro.id);
  if public.cm_overlaps(v_pro.id, v_date, v_hour, (v_presta ->> 'dur')::int, v_staff) then
    raise exception 'Ce créneau chevauche un autre rendez-vous. Choisissez une autre heure.';
  end if;
  begin
    insert into public.bookings (pro_id, client_id, presta_k, label, service, hair, price, hair_length, photos, staff, staff_name, dur,
      slot_date, slot_hour, first_name, phone, address, travel, hair_profile, status)
    values (v_pro.id, v_uid, v_presta ->> 'k', v_presta ->> 'label', v_presta ->> 'service', v_hair, v_price, v_length, v_photos, v_staff, v_sname,
      (v_presta ->> 'dur')::int, v_date, v_hour, v_first, v_phone, v_address, case when v_home then v_pro.travel else 0 end,
      coalesce(case when jsonb_typeof(p -> 'hair_profile') = 'object' and p -> 'hair_profile' <> '{}'::jsonb then p -> 'hair_profile' end, v_prof.hair, '{}'::jsonb),
      case when v_pro.is_example then 'confirmed' else 'pending' end)
    returning id into v_id;
  exception when unique_violation then
    raise exception 'Ce créneau vient d''être pris. Choisissez-en un autre.';
  end;
  update public.profiles set phone = v_phone, address = case when v_home then v_address else address end where id = v_uid;
  if not v_pro.is_example then
    perform public.cm_mail(v_pro.owner, 'booking_new', 'Nouvelle demande de rendez-vous',
      v_first || ' demande « ' || (v_presta ->> 'label') || ' » le ' || public.cm_date_label(v_date) || ' à ' || v_hour || '. Acceptez ou refusez depuis votre espace coiffeur.');
  end if;
  perform public.cm_mail(v_uid, 'booking_sent', case when v_pro.is_example then 'Votre rendez-vous est confirmé' else 'Votre demande est envoyée' end,
    (v_presta ->> 'label') || ' chez ' || v_pro.name || ', le ' || public.cm_date_label(v_date) || ' à ' || v_hour || '.');
  return v_id;
end $$;

create or replace function public.cm_set_status(p_id bigint, p_status text) returns void
language plpgsql security definer set search_path = public as $$
declare b public.bookings;
begin
  select * into b from public.bookings where id = p_id for update;
  update public.bookings set status = p_status, updated = now() where id = p_id;
  if p_status in ('refused', 'cancelled', 'expired') then perform public.cm_waitlist_notify(b.pro_id, b.slot_date, b.client_id); end if;
end $$;
revoke execute on function public.cm_set_status(bigint, text) from public, anon, authenticated;

create or replace function public.cm_cancel(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare b public.bookings; v_pro public.pros; v_is_client boolean; v_is_pro boolean; v_late boolean; s public.settings := public.cm_settings();
begin
  select * into b from public.bookings where id = p_id;
  if not found then raise exception 'Rendez-vous introuvable.'; end if;
  select * into v_pro from public.pros where id = b.pro_id;
  v_is_client := b.client_id = auth.uid(); v_is_pro := v_pro.owner = auth.uid();
  if not v_is_client and not v_is_pro then raise exception 'Ce rendez-vous ne vous concerne pas.'; end if;
  if b.status not in ('pending', 'confirmed') or (b.slot_date + b.slot_hour::time) <= public.cm_now() then raise exception 'Ce rendez-vous ne peut plus être annulé.'; end if;
  v_late := (b.slot_date + b.slot_hour::time) <= public.cm_now() + make_interval(hours => s.cancel_hours);
  perform public.cm_set_status(p_id, 'cancelled');
  if v_is_pro and not v_is_client then
    perform public.cm_mail(b.client_id, 'cancelled', 'Votre rendez-vous est annulé', v_pro.name || ' a annulé votre rendez-vous du ' || public.cm_date_label(b.slot_date) || ' à ' || b.slot_hour || '.');
  elsif not v_pro.is_example then
    perform public.cm_mail(v_pro.owner, 'cancelled', 'Un rendez-vous est annulé', b.first_name || ' a annulé son rendez-vous du ' || public.cm_date_label(b.slot_date) || ' à ' || b.slot_hour || '.');
  end if;
  return jsonb_build_object('ok', true, 'late', v_late);
end $$;

